"""Exercise all 12 approved SPEC-013 sources locally with the reader role.

Only counts, byte sizes and contract hashes are reported. No model/provider is
called, no SQL is generated by a model, and databases remain read-only.
"""

import argparse
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "inference_api/src"))
from inference_api.agent_harness import local_queries  # noqa: E402
from inference_api.agent_harness.approved_catalog import load  # noqa: E402


PLANS = [
    {"fonte_id": name, "campos": fields, "filtros": filters,
     "limite": 1 if name == "trace" else 20, "grao": grain}
    for name, fields, filters, grain in (
        ("machine", ["machine_id", "downtime_rows", "downtime_minutes"],
         {"year": 2021, "id": 2000002}, "machine_id/year"),
        ("product", ["product_id", "sale_rows", "observed_sales_value"],
         {"year": 2021, "id": 2000001}, "product_id/year"),
        ("financial", ["observation_id", "observed_day", "reported_net_profit"],
         {"year": 2021}, "observation_id/date"),
        ("quality", ["product_id", "inspection_rows"],
         {"year": 2021, "id": 2000001}, "product_id/year"),
        ("material", ["material_id", "consumption_rows"],
         {"year": 2021, "id": 2000001}, "material_id/year"),
        ("contributors", local_queries.LINEAGE_FIELDS["contributors"],
         {"kind": "machine", "year": 2021, "id": 2000002,
          "fact": "fact_downtime", "after": 0}, "aggregate_row/fact_id"),
        ("trace", local_queries.LINEAGE_FIELDS["trace"],
         {"fact": "fact_downtime", "id": 2900057}, "fact_id/source_row"),
        ("paradas_maquinas", ["parada_id", "maquina_id", "hora_inicio_parada"],
         {"parada_id": 1}, "parada_id/source_period"),
        ("paradas_maquinas_geradas", ["parada_id", "maquina_id", "origem"],
         {"parada_id": 2900057}, "parada_id/source_period"),
        ("registros_operacao", ["registro_id", "maquina_id", "quantidade_produzida_real"],
         {"registro_id": 1}, "registro_id/source_period"),
        ("resultados_financeiros", ["id", "data_registro", "lucro_liquido"],
         {"id": 2000001}, "id/observation_date/source_period"),
        ("vendas", ["venda_id", "data_venda", "preco_unitario_venda"],
         {"venda_id": 2000004}, "venda_id/source_period"),
    )
]


def verify() -> dict:
    catalog = load()
    sources = {source_id for domain in catalog["domains"].values()
               for source_id in domain["sources"]}
    if sources != {plan["fonte_id"] for plan in PLANS}:
        raise RuntimeError("Smoke plans do not cover exactly the approved source list")
    results = []
    for plan in PLANS:
        result = local_queries.execute(plan, catalog)
        if result["origin"].get("data_contract_sha256") != local_queries.DATA_CONTRACT_SHA256:
            raise RuntimeError("Data contract hash missing from result")
        if result["coverage"]["rows"] != len(result["rows"]):
            raise RuntimeError("Coverage/row mismatch")
        results.append({"source_id": plan["fonte_id"],
                        "rows": len(result["rows"]),
                        "state": result["coverage"]["state"],
                        "bytes": len(json.dumps(result, ensure_ascii=False,
                                                sort_keys=True).encode("utf-8"))})
    return {"mode": "approved_catalog_local_read_only",
            "approved_catalog_path": "specs/active/SPEC-013/catalog/pilot_local_v1.json",
            "sources_checked": len(results),
            "data_contract_sha256": local_queries.DATA_CONTRACT_SHA256,
            "dw_source_fingerprint": catalog["dw_source_fingerprint"],
            "reader_role": "spec013_reader", "provider_called": False,
            "scientific_score": None, "results": results}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = verify()
    rendered = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    if args.output:
        args.output.open("x", encoding="utf-8").write(rendered)
    else:
        print(rendered, end="")
